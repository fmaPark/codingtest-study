WITH RECURSIVE H AS (
    SELECT 0 AS HOUR
    UNION ALL
    SELECT HOUR + 1 FROM H
     WHERE HOUR < 23
)
SELECT 
       A.HOUR AS HOUR,
       COUNT(B.ANIMAL_ID) AS COUNT
  FROM H AS A
       LEFT JOIN ANIMAL_OUTS AS B
              ON DATE_FORMAT(B.DATETIME, '%H') = A.HOUR
 GROUP 
    BY HOUR
 ORDER
    BY HOUR
