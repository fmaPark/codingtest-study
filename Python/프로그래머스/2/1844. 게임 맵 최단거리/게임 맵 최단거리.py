from collections import deque

def solution(maps):
    n = len(maps)
    m = len(maps[0])
    
    # 시작 또는 도착 지점이 벽이면 즉시 -1
    if maps[0][0] == 0 or maps[n-1][m-1] == 0:
        return -1
    
    directions = [(-1, 0), (1, 0), (0, -1), (0, 1)]
    visited = [[False] * m for _ in range(n)]
    queue = deque()
    
    queue.append((0, 0, 1))  # (행, 열, 거리)
    visited[0][0] = True
    
    while queue:
        r, c, dist = queue.popleft()
        
        if r == n - 1 and c == m - 1:
            return dist
        
        for dr, dc in directions:
            nr, nc = r + dr, c + dc
            if 0 <= nr < n and 0 <= nc < m and not visited[nr][nc] and maps[nr][nc] == 1:
                visited[nr][nc] = True
                queue.append((nr, nc, dist + 1))
    
    return -1


